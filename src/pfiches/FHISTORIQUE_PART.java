private void afficherHistoriqueDepots() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); // Réinitialise le tableau

    String filtre = (String) jComboBox1.getSelectedItem();
    ArrayList<String[]> lignesDepots = new ArrayList<>();

    try (BufferedReader br = new BufferedReader(new FileReader("depots.txt"))) {
        String ligne;
        while ((ligne = br.readLine()) != null) {
            String[] parts = ligne.split(";");
            if (parts.length >= 5) {
                String mailUtilisateur = parts[0];
                String type = parts[1];
                String poids = parts[2];
                String date = parts[3];
                String mailCentre = parts[4];

                if (!mailUtilisateur.equals(FAccueil.mailEntreprise)) continue;

                // Recherche des infos du centre
                String nomCentre = "Inconnu";
                String adresse = "";
                try (BufferedReader brCentre = new BufferedReader(new FileReader("utilisateurs.txt"))) {
                    String ligneCentre;
                    while ((ligneCentre = brCentre.readLine()) != null) {
                        if (ligneCentre.startsWith("CENTRE")) {
                            String[] centreParts = ligneCentre.split(";");
                            if (centreParts.length >= 5 && centreParts[2].equals(mailCentre)) {
                                nomCentre = centreParts[1];
                                adresse = centreParts[4];
                                break;
                            }
                        }
                    }
                }

                lignesDepots.add(new String[]{nomCentre, date, type, poids, adresse});
            }
        }
    } catch (IOException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Erreur lors de la lecture de depots.txt", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Appliquer le tri selon le filtre
    switch (filtre) {
        case "Date croissant" -> lignesDepots.sort(Comparator.comparing(
            a -> LocalDate.parse(a[1], DateTimeFormatter.ofPattern("dd/MM/yyyy"))
        ));
        case "Date décroissant" -> lignesDepots.sort(Comparator.comparing(
            (String[] a) -> LocalDate.parse(a[1], DateTimeFormatter.ofPattern("dd/MM/yyyy"))
        ).reversed());
        case "Poids" -> lignesDepots.sort(Comparator.comparingDouble(
            a -> Double.valueOf(a[3])
        ));
        case "Type de déchet" -> lignesDepots.sort(Comparator.comparing(a -> a[2].toLowerCase()));
        case "Adresse" -> lignesDepots.sort(Comparator.comparing(a -> a[4].toLowerCase()));
        default -> {
            // "Tous" : pas de tri
        }
    }

    for (String[] ligne : lignesDepots) {
        model.addRow(new Object[]{ligne[0], ligne[1], ligne[2], ligne[3] + " kg", ligne[4]});
    }

    if (model.getRowCount() == 0) {
        model.addRow(new Object[]{"Aucun dépôt trouvé", "", "", "", ""});
    }
}




