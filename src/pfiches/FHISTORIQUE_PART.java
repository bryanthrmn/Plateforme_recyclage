    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    int selectedRow = jTable1.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Veuillez sélectionner un dépôt.", "Aucune sélection", JOptionPane.WARNING_MESSAGE);
        return;
    }

    String nomCentre = jTable1.getValueAt(selectedRow, 0).toString();

    // Rechercher les infos du centre dans utilisateurs.txt
    String types = "";
    String adresse = "";
    String ouverture = "";
    String fermeture = "";
    String tel = "";

    try (BufferedReader br = new BufferedReader(new FileReader("utilisateurs.txt"))) {
        String ligne;
        while ((ligne = br.readLine()) != null) {
            if (ligne.startsWith("CENTRE")) {
                String[] parts = ligne.split(";");
                if (parts.length >= 9 && parts[1].equalsIgnoreCase(nomCentre)) {
                    adresse = parts[4];
                    tel = parts[5];
                    ouverture = parts[6];
                    fermeture = parts[7];

                    StringBuilder sbTypes = new StringBuilder();
                    for (int i = 9; i < parts.length; i++) {
                        sbTypes.append(parts[i]);
                        if (i < parts.length - 1) sbTypes.append(", ");
                    }
                    types = sbTypes.toString();
                    break;
                }
            }
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Erreur lors de la lecture des centres.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Affichage des infos
    JPanel panel = new JPanel(new GridLayout(0, 1));
    panel.add(new JLabel("Nom : " + nomCentre));
    panel.add(new JLabel("Types de déchets : " + types));
    panel.add(new JLabel("Adresse : " + adresse));
    panel.add(new JLabel("Ouverture : " + ouverture));
    panel.add(new JLabel("Fermeture : " + fermeture));
    panel.add(new JLabel("Téléphone : " + tel));

    JOptionPane.showMessageDialog(this, panel, "Informations sur le centre", JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_jButton1ActionPerformed

