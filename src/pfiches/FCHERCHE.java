private void mettreAJourAffichageCentres() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); // Réinitialise le tableau

    String filtre = (String) jComboBox1.getSelectedItem();
    ArrayList<Object[]> listeCentres = new ArrayList<>();

    try (BufferedReader br = new BufferedReader(new FileReader("utilisateurs.txt"))) {
        String ligne;
        while ((ligne = br.readLine()) != null) {
            String[] parts = ligne.split(";");
            if (parts.length >= 9 && parts[0].equals("CENTRE")) {
                String nomCentre = parts[1].trim();
                String adresse = parts[4].trim();
                String telephone = parts[5].trim();
                String heureOuverture = parts[6].trim();
                String heureFermeture = parts[7].trim();
                String capacite = parts[8].trim(); // Capacité à afficher

                // Récupération des types de déchets
                StringBuilder typesDechets = new StringBuilder();
                for (int i = 9; i < parts.length; i++) {
                    typesDechets.append(parts[i].trim());
                    if (i < parts.length - 1) {
                        typesDechets.append(", ");
                    }
                }

                // Ajouter les données dans l'ordre demandé
                listeCentres.add(new Object[]{
                    nomCentre,
                    typesDechets.toString(),
                    adresse,
                    capacite + " kg",
                    heureOuverture,
                    heureFermeture,
                    telephone
                });
            }
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Erreur lors de la lecture de utilisateurs.txt", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Tri selon filtre sélectionné
    switch (filtre) {
        case "Centre" -> listeCentres.sort(Comparator.comparing(c -> c[0].toString().toLowerCase()));
        case "Type de déchets" -> listeCentres.sort(Comparator.comparing(c -> c[1].toString().toLowerCase()));
        case "Adresse" -> listeCentres.sort(Comparator.comparing(c -> c[2].toString().toLowerCase()));
        case "Capacité" -> listeCentres.sort(Comparator.comparingInt(c -> Integer.valueOf(c[3].toString().replace(" kg", ""))));
        default -> {
        }
    }
    // "Tous"

    // Affichage
    for (Object[] centre : listeCentres) {
        model.addRow(centre);
    }

    if (model.getRowCount() == 0) {
        model.addRow(new Object[]{"Aucun centre trouvé", "", "", "", "", "", ""});
    }

    jTable1.repaint();
}
