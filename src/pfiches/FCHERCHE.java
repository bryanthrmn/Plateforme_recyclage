@SuppressWarnings("empty-statement")
    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
    int selectedRow = jTable1.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Veuillez sélectionner un centre.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }

    String nomCentre = (String) jTable1.getValueAt(selectedRow, 0);

    // Recherche des infos du centre
    String adresse = "", mailCentre = "", capaciteMaxStr = "1000"; // valeur par défaut
    ArrayList<String> types = new ArrayList<>();
    try (BufferedReader br = new BufferedReader(new FileReader("utilisateurs.txt"))) {
        String ligne;
        while ((ligne = br.readLine()) != null) {
            if (ligne.startsWith("CENTRE")) {
                String[] parts = ligne.split(";");
                if (parts.length >= 10 && parts[1].equals(nomCentre)) {
                    mailCentre = parts[2];
                    adresse = parts[4];
                    capaciteMaxStr = parts[8];
                    for (int i = 9; i < parts.length; i++) {
                        types.add(parts[i]);
                    }
                    break;
                }
            }
        }
    } catch (IOException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Erreur lors du chargement des données du centre.", "Erreur", JOptionPane.ERROR_MESSAGE);
        return;
    }

    int capaciteMax = Integer.parseInt(capaciteMaxStr);

    // Création de la popup
    JPanel panel = new JPanel(new GridLayout(0, 2, 10, 10));
    panel.add(new JLabel("Centre :"));
    panel.add(new JLabel(nomCentre));

    panel.add(new JLabel("Adresse :"));
    panel.add(new JLabel(adresse));

    panel.add(new JLabel("Type de déchet :"));
    JComboBox<String> typeBox = new JComboBox<>(types.toArray(String[]::new));
    panel.add(typeBox);

    panel.add(new JLabel("Capacité (kg) :"));
    SpinnerNumberModel spinnerModel = new SpinnerNumberModel(1, 1, capaciteMax, 1);
    JSpinner capaciteSpinner = new JSpinner(spinnerModel);
    panel.add(capaciteSpinner);

    int result = JOptionPane.showConfirmDialog(this, panel, "Effectuer un dépôt", JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);

    if (result == JOptionPane.OK_OPTION) {
        String typeDechet = (String) typeBox.getSelectedItem();

        // Saisie manuelle à valider
        try {
            capaciteSpinner.commitEdit();
        } catch (ParseException e) {
            JOptionPane.showMessageDialog(this, "Valeur de poids invalide.", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int capacite = (int) capaciteSpinner.getValue();
        if (capacite > capaciteMax) {
            JOptionPane.showMessageDialog(this, "Le poids du déchet ne doit pas dépasser la capacité du centre", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String date = LocalDate.now().format(DateTimeFormatter.ofPattern("dd/MM/yyyy"));

        try (BufferedWriter writer = new BufferedWriter(new FileWriter("depots.txt", true))) {
            writer.write(FAccueil.mailEntreprise + ";" + typeDechet + ";" + capacite + ";" + date + ";" + mailCentre);
            writer.newLine();
            JOptionPane.showMessageDialog(this, "Dépôt enregistré avec succès !");
        } catch (IOException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erreur lors de l'enregistrement du dépôt.", "Erreur", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_jButton4ActionPerformed

